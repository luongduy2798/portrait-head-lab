import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const envText = await readFile(join(root, '.env'), 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return '';
  throw error;
});
const fileEnv = Object.fromEntries(envText.split(/\r?\n/).flatMap((line) => {
  const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
  if (!match) return [];
  const value = match[2].replace(/^(?:"(.*)"|'(.*)')$/, (_, doubleQuoted, singleQuoted) => doubleQuoted ?? singleQuoted);
  return [[match[1], value]];
}));

const configured = process.env.ML_PORTRAIT_HEAD_ASSET_BASE_URL
  ?? fileEnv.ML_PORTRAIT_HEAD_ASSET_BASE_URL
  ?? 'https://static.moodlab.dev/portrait-head/';
const url = new URL(configured.trim());
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) {
  throw new Error('ML_PORTRAIT_HEAD_ASSET_BASE_URL phải là HTTPS URL không có credentials, query hoặc hash.');
}

const assetBaseUrl = `${url.origin}${url.pathname.replace(/\/+$/, '')}/`;
await writeFile(join(root, 'portrait-head.config.js'),
  `/** Generated by tooling/configure-assets.mjs. */\nexport default Object.freeze({ assetBaseUrl: ${JSON.stringify(assetBaseUrl)} });\n`);
console.log(`Configured Portrait Head asset CDN: ${assetBaseUrl}`);
